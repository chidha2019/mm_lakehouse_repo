USE DATABASE MM_REFERENCE;
-- Policy-level annualized premium fact; current-state grain is policy_id.
MERGE INTO CURATED.FACT_POLICY_PREMIUM t
USING (
 SELECT p.POLICY_ID,p.CUSTOMER_ID,p.PRODUCT_ID,pr.LINE_OF_BUSINESS,
 p.POLICY_STATUS,p.ANNUAL_PREMIUM,p.EFFECTIVE_DATE
 FROM SILVER.POLICY p JOIN SILVER.INSURANCE_PRODUCT pr ON p.PRODUCT_ID=pr.PRODUCT_ID
 WHERE p.ANNUAL_PREMIUM >= 0
) s ON t.POLICY_ID=s.POLICY_ID
WHEN MATCHED THEN UPDATE SET t.CUSTOMER_ID=s.CUSTOMER_ID,t.PRODUCT_ID=s.PRODUCT_ID,
 t.LINE_OF_BUSINESS=s.LINE_OF_BUSINESS,t.POLICY_STATUS=s.POLICY_STATUS,
 t.ANNUAL_PREMIUM=s.ANNUAL_PREMIUM,t.EFFECTIVE_DATE=s.EFFECTIVE_DATE,t.UPDATED_AT_PIPELINE=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (POLICY_ID,CUSTOMER_ID,PRODUCT_ID,LINE_OF_BUSINESS,POLICY_STATUS,ANNUAL_PREMIUM,EFFECTIVE_DATE,UPDATED_AT_PIPELINE)
 VALUES(s.POLICY_ID,s.CUSTOMER_ID,s.PRODUCT_ID,s.LINE_OF_BUSINESS,s.POLICY_STATUS,s.ANNUAL_PREMIUM,s.EFFECTIVE_DATE,CURRENT_TIMESTAMP());
-- Position fact: current holding snapshot grain account+symbol+date. No market feeds; synthetic marked price.
MERGE INTO CURATED.FACT_WEALTH_POSITION t
USING (
 SELECT a.ACCOUNT_ID,a.CUSTOMER_ID,a.ADVISOR_ID,h.SECURITY_SYMBOL,h.AS_OF_DATE,
 SUM(h.QUANTITY*h.MARKET_PRICE)::NUMBER(22,4) AS POSITION_VALUE
 FROM SILVER.WEALTH_ACCOUNT a JOIN SILVER.HOLDING h ON a.ACCOUNT_ID=h.ACCOUNT_ID
 WHERE a.ACCOUNT_STATUS='OPEN'
 GROUP BY 1,2,3,4,5
) s ON t.ACCOUNT_ID=s.ACCOUNT_ID AND t.SECURITY_SYMBOL=s.SECURITY_SYMBOL AND t.AS_OF_DATE=s.AS_OF_DATE
WHEN MATCHED THEN UPDATE SET t.CUSTOMER_ID=s.CUSTOMER_ID,t.ADVISOR_ID=s.ADVISOR_ID,
 t.POSITION_VALUE=s.POSITION_VALUE,t.UPDATED_AT_PIPELINE=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (ACCOUNT_ID,CUSTOMER_ID,ADVISOR_ID,SECURITY_SYMBOL,AS_OF_DATE,POSITION_VALUE,UPDATED_AT_PIPELINE)
 VALUES(s.ACCOUNT_ID,s.CUSTOMER_ID,s.ADVISOR_ID,s.SECURITY_SYMBOL,s.AS_OF_DATE,s.POSITION_VALUE,CURRENT_TIMESTAMP());
-- Demonstration snapshot uses first day of the current month; re-running updates this month's rows.
MERGE INTO CURATED.MONTHLY_PREMIUM_BY_PRODUCT t
USING (
 SELECT DATE_TRUNC('MONTH',CURRENT_DATE())::DATE AS PREMIUM_MONTH,
 PRODUCT_ID,LINE_OF_BUSINESS,COUNT(*) AS ACTIVE_POLICY_COUNT,
 SUM(ANNUAL_PREMIUM)::NUMBER(22,2) AS TOTAL_ANNUALIZED_PREMIUM
 FROM CURATED.FACT_POLICY_PREMIUM WHERE POLICY_STATUS='ACTIVE'
 GROUP BY 1,2,3
) s ON t.PREMIUM_MONTH=s.PREMIUM_MONTH AND t.PRODUCT_ID=s.PRODUCT_ID
WHEN MATCHED THEN UPDATE SET t.LINE_OF_BUSINESS=s.LINE_OF_BUSINESS,
 t.ACTIVE_POLICY_COUNT=s.ACTIVE_POLICY_COUNT,t.TOTAL_ANNUALIZED_PREMIUM=s.TOTAL_ANNUALIZED_PREMIUM,t.UPDATED_AT_PIPELINE=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (PREMIUM_MONTH,PRODUCT_ID,LINE_OF_BUSINESS,ACTIVE_POLICY_COUNT,TOTAL_ANNUALIZED_PREMIUM,UPDATED_AT_PIPELINE)
 VALUES(s.PREMIUM_MONTH,s.PRODUCT_ID,s.LINE_OF_BUSINESS,s.ACTIVE_POLICY_COUNT,s.TOTAL_ANNUALIZED_PREMIUM,CURRENT_TIMESTAMP());
