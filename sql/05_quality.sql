USE DATABASE MM_REFERENCE;
-- SQL assertions fail the run when violated. COUNT values expected to be zero.
SELECT CASE WHEN COUNT(*)=0 THEN 'PASS' ELSE 'FAIL' END AS POLICY_KEYS_UNIQUE
 FROM (SELECT POLICY_ID FROM SILVER.POLICY GROUP BY POLICY_ID HAVING COUNT(*)>1);
SELECT CASE WHEN COUNT(*)=0 THEN 'PASS' ELSE 'FAIL' END AS POLICY_REFERENCES_VALID
 FROM SILVER.POLICY p LEFT JOIN SILVER.CUSTOMER c ON p.CUSTOMER_ID=c.CUSTOMER_ID
 WHERE c.CUSTOMER_ID IS NULL;
SELECT CASE WHEN COUNT(*)=0 THEN 'PASS' ELSE 'FAIL' END AS PREMIUM_NONNEGATIVE
 FROM CURATED.FACT_POLICY_PREMIUM WHERE ANNUAL_PREMIUM<0;
SELECT CASE WHEN COUNT(*)=0 THEN 'PASS' ELSE 'FAIL' END AS WEALTH_POSITIONS_NONNEGATIVE
 FROM CURATED.FACT_WEALTH_POSITION WHERE POSITION_VALUE<0;
